import type { Action, Evidence, InteractionKind, Mode, Purpose, StimulusOption, Surface } from "./protocol.ts";

/**
 * What the host page needs from the learning backend (D-306). The host is the only party that calls it,
 * with the pupil's own session. Two implementations exist:
 *
 *   - `FakeTaskService` (test-service.ts): a TEST ADAPTER with in-memory items, used by unit tests and the
 *     local Arkivskabet prototype. It is not the server and proves nothing about the server.
 *   - a real adapter over get-next-question / process-event (not built; see docs/decisions/D-306.md §Trin B).
 *
 * The service owns grading, answer keys, hints, evidence and rewards. Nothing it returns is an answer key
 * before the instance is closed.
 */
export interface ServiceTask {
  /** The server's instance id. Never shown to the game: the host maps it to an opaque token. */
  readonly instanceId: string;
  readonly kind: InteractionKind;
  readonly prompt: string;
  readonly options: readonly StimulusOption[] | null;
  readonly mode: Mode;
  readonly hintsAvailable: number;
  readonly contextKey: string;
  /** Answer round on the server (H5 `round_no`). */
  readonly roundNo: number;
}

export interface TaskQuery {
  readonly objectiveId: string;
  readonly purpose: Purpose;
  readonly surface: Surface;
  readonly kinds: readonly InteractionKind[];
  readonly contextKey: string;
}

export interface Submission {
  readonly instanceId: string;
  readonly roundNo: number;
  /** Generated by the host once per instance and round; the same id on every retry (H5 idempotency). */
  readonly submissionId: string;
  readonly action: Action;
}

export interface ServiceResult {
  readonly outcome: "correct" | "incorrect" | "pending";
  readonly feedbackText: string | null;
  readonly correctAnswer: string | null;
  readonly evidence: Evidence;
  /** true when this is the stored result of an earlier identical submission (no new effect). */
  readonly replay: boolean;
}

export interface ServiceHint {
  readonly level: number;
  readonly text: string;
  readonly hintsRemaining: number;
}

/**
 * A failure of the backend. `transient` failures (network, timeout, 5xx) are retried with the same
 * submission id; permanent ones are reported to the game at once.
 */
export class ServiceError extends Error {
  readonly code: "network" | "timeout" | "forbidden" | "not_found" | "invalid" | "unavailable" | "server" | "unauthorized" | "outdated";
  readonly transient: boolean;
  constructor(code: ServiceError["code"], transient: boolean, message?: string) {
    super(message ?? code);
    this.name = "ServiceError";
    this.code = code;
    this.transient = transient;
  }
}

/**
 * Whether resending a submission after an ambiguous failure (no response, timeout, 5xx) is safe.
 * "server-idempotent": the backend itself guarantees that a resend can neither record nor pay twice and
 * returns the original verdict. "none": no such guarantee — the host must not resend automatically.
 */
export type SubmitRetry = "server-idempotent" | "none";

export interface TaskService {
  readonly submitRetry: SubmitRetry;
  /** The pupil's open instance, if any (resumption: one open instance per pupil on the server). */
  openTask(): Promise<ServiceTask | null>;
  fetchTask(query: TaskQuery): Promise<ServiceTask>;
  submit(submission: Submission): Promise<ServiceResult>;
  hint(instanceId: string, level: number): Promise<ServiceHint>;
}
