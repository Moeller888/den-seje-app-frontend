"""Generate the demo's spritesheets and sounds (phase 4).

Everything is drawn or synthesised here from scratch: simple SVG shapes and
sine/square tones. There is no randomness, so the output is byte-for-byte
reproducible. Licence: the same as the project; no third-party material.

Run from the project root:  python -I tools/media/gen-demo-media.py
Writes packages/app/public/assets/*-atlas.svg and packages/app/public/media/*.wav
"""
import io
import math
import os
import struct
import wave

ASSETS = "packages/app/public/assets"
MEDIA = "packages/app/public/media"
HEADER = "<!-- Generated by tools/media/gen-demo-media.py (project-made placeholder art). -->\n"


def svg_sheet(path, fw, fh, frames, columns=None):
    cols = columns or len(frames)
    rows = (len(frames) + cols - 1) // cols
    parts = []
    for i, body in enumerate(frames):
        x, y = (i % cols) * fw, (i // cols) * fh
        parts.append(f'<g transform="translate({x} {y})">{body}</g>')
    w, h = cols * fw, rows * fh
    with io.open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write(f'<svg xmlns="http://www.w3.org/2000/svg" width="{w}" height="{h}" viewBox="0 0 {w} {h}">\n{HEADER}' + "\n".join(parts) + "\n</svg>\n")


def mirror(body, fw):
    return f'<g transform="translate({fw} 0) scale(-1 1)">{body}</g>'


# --- Tove: 60 x 170 frames. Frame 0 is exactly assets/tove.svg. -------------------
def tove(legs, head_dx=0, bob=0):
    return (
        f'<path d="{legs}" fill="#3b4a6b"/>'
        f'<g transform="translate(0 {bob})">'
        '<path d="M10 110 Q8 60 30 52 Q52 60 50 110 Z" fill="#c4553a"/>'
        f'<g transform="translate({head_dx} 0)">'
        '<circle cx="30" cy="32" r="20" fill="#e9c4a0"/>'
        '<path d="M10 30 Q12 6 30 8 Q50 6 50 30 Q44 18 30 18 Q16 18 10 30 Z" fill="#6b3f22"/>'
        '<circle cx="23" cy="34" r="2.5" fill="#222"/><circle cx="37" cy="34" r="2.5" fill="#222"/>'
        "</g></g>"
    )


STAND_LEGS = "M12 170 L16 105 L44 105 L48 170 L36 170 L30 120 L24 170 Z"


def walk_legs(phase):
    # Two legs swinging in opposite directions around the hip line.
    s = math.sin(phase * math.pi / 2) * 14
    a, b = round(18 - s), round(42 + s)
    return f"M{a - 6} 170 L18 105 L30 105 L{a + 6} 170 Z M{b - 6} 170 L30 105 L42 105 L{b + 6} 170 Z"


right = [tove(STAND_LEGS)] + [tove(walk_legs(p), bob=(-2 if p % 2 else 0)) for p in range(4)]
cannot = [tove(STAND_LEGS, head_dx=-3), tove(STAND_LEGS, head_dx=3)]
# 0 stand.right, 1-4 walk.right, 5 stand.left, 6-9 walk.left, 10-11 cannot
svg_sheet(f"{ASSETS}/tove-atlas.svg", 60, 170, right + [mirror(b, 60) for b in right] + cannot)

