# --- Sounds: 11025 Hz, 8-bit mono PCM WAV. -------------------------------------------
RATE = 11025


def write_wav(path, samples):
    with wave.open(path, "wb") as w:
        w.setnchannels(1)
        w.setsampwidth(1)
        w.setframerate(RATE)
        w.writeframes(bytes(max(0, min(255, round(128 + 120 * s))) for s in samples))


def tone(freq, seconds, volume=0.6, decay=0.0, square=False):
    n = int(RATE * seconds)
    out = []
    for i in range(n):
        t = i / RATE
        v = math.sin(2 * math.pi * freq * t)
        if square:
            v = 1.0 if v >= 0 else -1.0
        env = math.exp(-decay * t) if decay else 1.0
        out.append(volume * v * env)
    return out


os.makedirs(MEDIA, exist_ok=True)
# Pick-up blip: two short rising tones.
write_wav(f"{MEDIA}/pickup.wav", tone(660, 0.08, 0.5, 20) + tone(990, 0.12, 0.5, 18))
# Room hum: 2 s, frequencies with whole cycles in 2 s so the loop is seamless.
hum = [0.25 * math.sin(2 * math.pi * 55 * i / RATE) + 0.12 * math.sin(2 * math.pi * 110 * i / RATE) for i in range(RATE * 2)]
write_wav(f"{MEDIA}/hum.wav", hum)
# Theme: a short four-note phrase, 4 s, soft attack and release per note.
theme = []
for note in [392, 330, 349, 294]:
    seg = tone(note, 1.0, 0.35)
    k = len(seg)
    theme += [s * min(1.0, i / 400, (k - i) / 1200) for i, s in enumerate(seg)]
write_wav(f"{MEDIA}/theme.wav", theme)
print("ok")
