# 0 stand, 1-3 flap (wing up, high, up)
svg_sheet(f"{ASSETS}/crow-atlas.svg", 80, 90, [crow("M14 50 L0 70 L22 62 Z"), crow("M16 48 L0 30 L26 52 Z"), crow("M18 46 L6 8 L30 48 Z"), crow("M16 48 L0 30 L26 52 Z")])

# --- Clock: 100 x 300 frames: 0-3 swing, 4-5 chime. ---------------------------------
def clock(angle, ring=0):
    x = 50 + round(math.sin(math.radians(angle)) * 108)
    y = 118 + round(math.cos(math.radians(angle)) * 108)
    glow = f'<circle cx="50" cy="55" r="{40 + ring}" fill="none" stroke="#f6d86b" stroke-width="{3 + ring // 3}" opacity="0.8"/>'
    return (
        '<rect x="10" y="0" width="80" height="300" rx="10" fill="#6b3f22" stroke="#3a2212" stroke-width="5"/>'
        '<circle cx="50" cy="55" r="34" fill="#f2ead2" stroke="#3a2212" stroke-width="4"/>'
        '<rect x="28" y="110" width="44" height="160" rx="6" fill="#3a2212"/>'
        '<line x1="50" y1="55" x2="72" y2="48" stroke="#222" stroke-width="4"/><line x1="50" y1="55" x2="40" y2="34" stroke="#222" stroke-width="3"/>'
        f'<line x1="50" y1="118" x2="{x}" y2="{y}" stroke="#e2c65a" stroke-width="3"/><circle cx="{x}" cy="{y + 6}" r="12" fill="#e2c65a"/>'
        + glow
    )


svg_sheet(f"{ASSETS}/clock-atlas.svg", 100, 300, [clock(-8), clock(0), clock(8), clock(0), clock(0, 12), clock(0, 24)])

# --- Story cutscene pictures (timeline frames), 1280 x 720. --------------------------
def picture(path, sky, sun, caption_shape):
    with io.open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write(
            '<svg xmlns="http://www.w3.org/2000/svg" width="1280" height="720" viewBox="0 0 1280 720">\n' + HEADER
            + f'<rect width="1280" height="720" fill="{sky}"/><circle cx="{sun[0]}" cy="{sun[1]}" r="90" fill="#f6e3a1"/>'
            + '<path d="M0 520 Q320 440 640 500 T1280 480 L1280 720 L0 720 Z" fill="#4f7a45"/>'
            + caption_shape + "\n</svg>\n"
        )


