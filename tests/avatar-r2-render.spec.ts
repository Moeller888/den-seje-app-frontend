let adminClient: ReturnType<typeof createClient>;
let studentId: string;

const NEUTRAL_MEDIUM = () => ({ v: 1, body_type: "neutral", hairstyle: "tousled", skin_tone: "medium", hair_color: "brown", chosen_at: new Date().toISOString() });
const BASE_IDENTITY  = () => ({ v: 1, body_type: "neutral", hairstyle: "default", skin_tone: "medium", chosen_at: new Date().toISOString() });

test.beforeAll(async () => {
  adminClient = createClient(SUPABASE_URL, SUPABASE_SERVICE_ROLE_KEY, { auth: { autoRefreshToken: false, persistSession: false } });
  const loginClient = createClient(SUPABASE_URL, SUPABASE_ANON_KEY, { auth: { autoRefreshToken: false, persistSession: false } });
  const { data: session, error } = await loginClient.auth.signInWithPassword({ email: STUDENT_EMAIL, password: STUDENT_PASS });
  if (error || !session.session) throw new Error(`Student sign-in failed: ${error?.message}`);
  studentId = session.user!.id;
});

// Per-browser R2 opt-in (+ C2 pipeline enable). Runs before every page script.
test.beforeEach(async ({ page }) => {
  await page.addInitScript(() => {
    try { localStorage.setItem("avatar_v2", "1"); localStorage.setItem("avatar_r2", "1"); } catch (e) {}
  });
});

test.afterAll(async () => {
  // Restore the shared student to the default identity + empty cosmetics.
  await adminClient.from("profiles").update({ equipped_slots: {}, avatar_identity: BASE_IDENTITY() }).eq("id", studentId);
});

async function setIdentity(identity: object) {
  const { error } = await adminClient.from("profiles").update({ avatar_identity: identity }).eq("id", studentId);
  if (error) throw new Error(`identity fixture failed: ${error.message}`);
}

async function loginReduced(page: any) {
  await page.emulateMedia({ reducedMotion: "reduce" });
  await page.goto(`${PROD}/login.html`, { waitUntil: "domcontentloaded" });
  await page.fill("#email", STUDENT_EMAIL);
  await page.fill("#password", STUDENT_PASS);
  await page.locator("#loginBtn").click();
  await page.waitForURL(`${PROD}/index.html`, { timeout: 20000 });
}

// Wait for the app render-complete signal + assert the R2 stack (not C2) is active,
// so the golden can never silently bake in a C2 fallback.
async function waitForR2(page: any, selector: string) {
  await page.waitForSelector(`${selector}[data-avatar-rendered="1"]`, { timeout: 15000 });
  await expect(page.locator(`${selector} img[data-c2-layer="base"][src*="avatar-r2/base/body-neutral-medium-v2.webp"]`),
    "R2 base must be the active render (opt-in resolved)").toBeAttached({ timeout: 10000 });
  await page.waitForFunction(
    (sel: string) => {
      const imgs = Array.from(document.querySelectorAll(sel + " img"));
      return imgs.length > 0 && imgs.every((i: any) => i.complete && i.naturalWidth > 0);
    },
    selector,
    { timeout: 15000 }
  );
}

test("golden: R2 avatar page (neutral-medium) matches baseline", async ({ page, browserName }) => {
  test.skip(browserName !== "chromium", "golden baselines are chromium-only");
  await setIdentity(NEUTRAL_MEDIUM());
  await loginReduced(page);
  await page.goto(`${PROD}/avatar.html`, { waitUntil: "domcontentloaded" });
  await page.waitForSelector("#skinToneButtons .identity-btn", { timeout: 15000 });
  await waitForR2(page, "#avatar-preview");
  await expect(page.locator("#avatar-preview")).toHaveScreenshot("r2-avatar-page-neutral-medium.png", { maxDiffPixels: 250, animations: "disabled" });
});

