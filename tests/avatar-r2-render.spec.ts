// Avatar R2 render goldens (activation-audit F4). Permanent pixel baselines for
// the DECOMPOSED R2 raster stack (neutral × medium — the only R2-supported identity)
// on the avatar page, hub and quiz. Until now every avatar golden captured the C2
// path (AVATAR_R2=false); these are the first R2 baselines, so a future change to an
// R2 layer or the render path is caught by pixel regression.
//
// R2 is opted-in PER TEST BROWSER via localStorage (avatar_v2=1 + avatar_r2=1); the
// global AVATAR_R2 flag stays false. Reduced motion suppresses blink/presence/
// expression (js/avatar-blink-engine.js §"Suppressed under prefers-reduced-motion"),
// so the eyes/face are static → deterministic. chromium-only; baselines committed
// for chromium-win32 + chromium-linux (the latter regenerated by the manual
// Update-Avatar-Goldens workflow). Goldens live in
// tests/avatar-r2-render.spec.ts-snapshots/.

